const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { pathToFileURL } = require('node:url');
const sharp = require('sharp');
const { chromium } = require('playwright');
sharp.cache(false);

// Rebuild derived assets only; original artwork and lightbox URLs stay intact.
async function main() {
  const root = path.resolve(__dirname, '..');
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage();
  await page.route('**/*', (route) => route.request().resourceType() === 'image' ? route.abort() : route.continue());
  await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
  if (!await page.locator('#case-list img').count()) throw new Error('Case rendering failed; refusing an incomplete manifest.');
  const sources = await page.evaluate(() => [...new Set([
    ...[...document.querySelectorAll('img')].map(img => img.dataset.imageOriginal || img.getAttribute('src')),
    ...[...document.querySelectorAll('[data-full]')].map(el => el.dataset.full)
  ])].filter(src => src?.startsWith('assets/') && !src.startsWith('assets/previews/')));
  // This original is selected only after opening the calendar tab.
  sources.push('assets/c_xmu_media/c35_travel_calendar_full.png');
  const output = path.join(root, 'assets/previews');
  fs.mkdirSync(output, { recursive: true });
  const manifest = {};
  let originalBytes = 0;
  let smallBytes = 0;
  let largeBytes = 0;
  for (const src of [...new Set(sources)].sort()) {
    const buffer = fs.readFileSync(path.join(root, src));
    const meta = await sharp(buffer).metadata();
    const hash = crypto.createHash('sha256').update(buffer).update('preview-v1').digest('hex').slice(0, 12);
    const variants = [];
    for (const [name, edge, quality] of [['small', 720, 82], ['large', 1800, 86]]) {
      const file = `${hash}-${name}.webp`;
      const isLong = meta.height / meta.width > 3;
      const options = isLong
        ? { width: name === 'small' ? 480 : 1000, height: name === 'small' ? 3000 : 6000, fit: 'inside' }
        : { width: edge, height: edge, fit: 'inside' };
      if (!fs.existsSync(path.join(output, file)) || !fs.statSync(path.join(output, file)).size) {
        const encoded = await sharp(buffer).rotate().resize({ ...options, withoutEnlargement: true }).webp({ quality, effort: 5 }).toBuffer();
        fs.writeFileSync(path.join(output, file), encoded);
      }
      const info = await sharp(path.join(output, file)).metadata();
      const bytes = fs.statSync(path.join(output, file)).size;
      variants.push({ src: `assets/previews/${file}`, width: info.width, height: info.height, bytes });
    }
    manifest[src] = { width: meta.width, height: meta.height, small: variants[0], large: variants[1] };
    originalBytes += buffer.length;
    smallBytes += variants[0].bytes;
    largeBytes += variants[1].bytes;
  }
  fs.writeFileSync(path.join(root, 'image-previews.js'), `// Generated by tools/build-image-previews.cjs.\nwindow.portfolioImagePreviews = ${JSON.stringify(manifest)};\n`);
  // Static hero images need optimized URLs in HTML, before the preload scanner runs.
  const htmlPath = path.join(root, 'index.html');
  let html = fs.readFileSync(htmlPath, 'utf8');
  const replacements = await page.evaluate((map) => [...document.querySelectorAll('#profile img')].map(img => {
    const original = img.dataset.imageOriginal || img.getAttribute('src');
    const entry = map[original];
    if (!entry) return null;
    const before = img.outerHTML;
    img.classList.remove('image-unavailable', 'is-loaded');
    if (!img.className) img.removeAttribute('class');
    delete img.dataset.imageAttempt;
    img.dataset.imageOriginal = original;
    img.src = entry.small.src;
    const showcase = !!img.closest('.hero-showcase');
    if (!showcase) {
      img.srcset = `${entry.small.src} ${entry.small.width}w, ${entry.large.src} ${entry.large.width}w`;
      img.sizes = '(max-width: 600px) 70vw, 420px';
    }
    img.width = entry.width;
    img.height = entry.height;
    img.decoding = 'async';
    img.setAttribute('fetchpriority', showcase ? 'low' : 'high');
    return { original, before, after: img.outerHTML };
  }).filter(Boolean), manifest);
  for (const replacement of replacements) {
    // Match only existing static img tags; attributes come from the DOM serializer.
    const tags = html.match(/<img\b[^>]*>/g) || [];
    for (const tag of tags) {
      if (tag.includes(`"${replacement.original}"`)) html = html.replace(tag, replacement.after);
    }
  }
  fs.writeFileSync(htmlPath, html);
  fs.mkdirSync(path.join(root, '.codex-build'), { recursive: true });
  const report = { images: Object.keys(manifest).length, originalBytes, smallBytes, largeBytes };
  fs.writeFileSync(path.join(root, '.codex-build/image-preview-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
  await browser.close();
}
main().catch(error => { console.error(error); process.exit(1); });
